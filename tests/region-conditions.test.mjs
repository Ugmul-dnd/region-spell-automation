assert.equal(hasEquivalentActiveEffect({effects:[{...regionHalf,disabled:true}]},halfSpeed),false,"Inactive effects do not block application");
assert.equal(hasEquivalentActiveEffect({effects:[{uuid:"other",name:"Unrelated",system:{changes:[]}}]},halfSpeed),false);
